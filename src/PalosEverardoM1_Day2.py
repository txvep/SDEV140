# This program prompts the user to input two floating point numbers,
# multiplies them, and displays the result.

# Prompt the user for the first floating point number.
first_number = float(input("Enter the first floating point number: "))

# Prompt the user for the second floating point number.
second_number = float(input("Enter the second floating point number: "))

# Multiply the two numbers.
result = first_number * second_number

# Display the result.
print(f"The result of multiplying {first_number} and {second_number} is: {result}")
